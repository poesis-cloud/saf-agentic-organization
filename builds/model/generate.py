def mark_generated(rel, text):
    """Say in every generated file that it is generated: a YAML comment, the Markdown SPDX comment, a schema `$comment`."""
    if rel.endswith(".json"):
        data = json.loads(text)
        keys = list(data)
        at = keys.index("$id") + 1 if "$id" in keys else 0
        data = {**{k: data[k] for k in keys[:at]}, "$comment": GENERATED_NOTE, **{k: data[k] for k in keys[at:]}}
        return json.dumps(data, indent=2, ensure_ascii=False)
    if rel.endswith(".yaml"):
        assert text.startswith(YAML_HEADER), rel
        return YAML_HEADER + f"#\n# {GENERATED_NOTE}\n" + text[len(YAML_HEADER):]
    assert f"<!-- {SPDX}" in text, rel
    return text.replace(f"<!-- {SPDX}", f"<!-- {SPDX}. Generated: builds/model", 1)  # injected into agents: two words

def write(rel, text):
    text = mark_generated(rel, text)
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text if text.endswith("\n") else text + "\n", encoding="utf-8")

class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True

def dump_yaml(data):
    return yaml.dump(data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=10_000, default_flow_style=False)

